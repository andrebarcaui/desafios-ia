/* Partida simulada com um caso supervisionado e um de agrupamento. Rode: node tools/teste-core.js */
global.Stats = require('../shared/stats.js');
const SC = require('../shared/server-core.js');
const sup = require('../casos-fonte/ml-supervisionado/fuga-silenciosa.json');
const agr = require('../casos-fonte/ml-nao-supervisionado/tamanho-unico.json');
const mem = {}; let t = 1e12, falhas = 0;
const store = { get: k => mem[k] ? JSON.parse(mem[k]) : null, set: (k, v) => { mem[k] = JSON.stringify(v); }, del: k => { delete mem[k]; } };
const cfg = { chaveProfessor: '020271', grupos: [
  { codigo: 'S-1', nome: 'Grupo 1', caso: sup.id }, { codigo: 'S-2', nome: 'Grupo 2', caso: sup.id },
  { codigo: 'A-1', nome: 'Grupo 3', caso: agr.id }, { codigo: 'A-2', nome: 'Grupo 4', caso: agr.id }, { codigo: 'A-3', nome: 'Grupo 5', caso: agr.id }] };
const s = SC.create({ store, casos: { [sup.id]: sup, [agr.id]: agr }, config: cfg, agora: () => t });
const h = r => { const x = s.handle(Object.assign({ chave: '020271' }, r)); if (x && x.erro) { falhas++; console.log('ERRO', r.acao, r.codigo || '', x.erro); } return x; };
const ok = (c, msg) => { if (!c) { falhas++; console.log('FALHOU:', msg); } };
const gabCartas = caso => { const o = {}; caso.fases[1].itens[0].cartas.forEach(c => o[c.id] = c._gabarito); return o; };
const melhor = g => Object.keys(g).reduce((a, b) => g[b] > g[a] ? b : a);
const respF = (caso, fid) => { const o = {}; caso.fases.find(f => f.id === fid).itens.forEach(i => { if (i.tipo === 'escolha' && i._gabarito) o[i.id] = melhor(i._gabarito); if (i.tipo === 'texto') o[i.id] = 'ok'; }); return o; };

cfg.grupos.forEach(g => h({ acao: 'entrar', codigo: g.codigo, membros: ['Ana', 'Bia'] }));
ok(s.handle({ acao: 'prof_placar' }).erro, 'placar exige senha');
ok(s.handle({ acao: 'placar' }).erro, 'placar público não existe mais');
h({ acao: 'prof_fase', fase: 1 });
cfg.grupos.forEach(g => h({ acao: 'enviar', codigo: g.codigo, faseId: 'f1', respostas: respF(g.caso === sup.id ? sup : agr, 'f1') }));
t += 6e4 * 6; h({ acao: 'prof_fase', fase: 2 });
h({ acao: 'enviar', codigo: 'S-1', faseId: 'f2', respostas: { f2cartas: gabCartas(sup) } });
h({ acao: 'enviar', codigo: 'S-2', faseId: 'f2', respostas: { f2cartas: Object.assign(gabCartas(sup), { c11: 'feature' }) } });
h({ acao: 'comprar', codigo: 'A-1', fonteId: 'm1' });
h({ acao: 'enviar', codigo: 'A-1', faseId: 'f2', respostas: { f2cartas: gabCartas(agr) } });
h({ acao: 'enviar', codigo: 'A-2', faseId: 'f2', respostas: { f2cartas: gabCartas(agr) } });
h({ acao: 'enviar', codigo: 'A-3', faseId: 'f2', respostas: { f2cartas: Object.assign(gabCartas(agr), { c11: 'agrupar' }) } });
t += 6e4 * 12; h({ acao: 'prof_fase', fase: 3 });
h({ acao: 'treinar', codigo: 'S-1', respostas: { f3q1: 'b' } }); h({ acao: 'treinar', codigo: 'S-2', respostas: { f3q1: 'a' } });
h({ acao: 'enviar', codigo: 'S-1', faseId: 'f3', respostas: { f3q1: 'b', f3q2: 'b', f3sim: { pct: 5 } } });
h({ acao: 'enviar', codigo: 'S-2', faseId: 'f3', respostas: { f3q1: 'a', f3q2: 'a', f3sim: { pct: 6 } } });
const ta = h({ acao: 'treinar', codigo: 'A-1', respostas: { f3q1: 'b' } }).modelo;
ok(ta.tipo === 'agrupamento' && ta.perfis['4'].length === 4, 'perfis de agrupamento');
const te = h({ acao: 'treinar', codigo: 'A-2', respostas: { f3q1: 'a' } }).modelo;
console.log('silhuetas padronizado', JSON.stringify(ta.silhuetas), '| sem padronizar', JSON.stringify(te.silhuetas));
console.log('faixas sem padronizar k=3:', te.perfis['3'].map(p => p.n + ' ' + p.tracos[0]).join(' | '));
h({ acao: 'enviar', codigo: 'A-1', faseId: 'f3', respostas: { f3q1: 'b', f3q2: 'b', f3grupos: { k: 4 } } });
h({ acao: 'enviar', codigo: 'A-2', faseId: 'f3', respostas: { f3q1: 'a', f3q2: 'd', f3grupos: { k: 3 } } });
h({ acao: 'enviar', codigo: 'A-3', faseId: 'f3', respostas: { f3q1: 'b', f3q2: 'b', f3grupos: { k: 3 } } });
const p3 = h({ acao: 'prof_placar' });
console.log('Após f3:', p3.grupos.map(g => g.nome + ' ' + g.total + ' (' + (g.metrica && g.metrica.treino) + ')').join(' | '));
t += 6e4 * 8; h({ acao: 'prof_fase', fase: 4 });
['S-1', 'S-2', 'A-1', 'A-2', 'A-3'].forEach(c => { const e = h({ acao: 'estado', codigo: c }).evento; console.log(c, '>', e.titulo, '|', e.antes.valor, '->', e.depois.valor); });
const cen = { 'A-1': 'drift', 'A-2': 'escala', 'A-3': 'circular' };
Object.keys(cen).forEach(c => { const g = agr._evento[cen[c]]._gabarito; h({ acao: 'enviar', codigo: c, faseId: 'evento', respostas: { evq1: melhor(g.evq1), evq2: melhor(g.evq2) } }); });
h({ acao: 'prof_fase', fase: 5 });
const pv = h({ acao: 'prof_grupo', codigo: 'A-1' });
ok(pv.espiando && pv.ficha && pv.ficha.secoes.length === 4, 'professor vê a tela do grupo');
console.log('Ficha A-1:', pv.ficha.secoes[2].linhas.slice(0, 4).map(l => l.rotulo + ': ' + l.valor).join(' / '));
h({ acao: 'prof_fase', fase: 6 });
const pf = h({ acao: 'prof_placar' });
console.log('Final:', pf.grupos.map(g => g.nome + ' ' + g.total + ' ' + JSON.stringify(g.pontos)).join('\n       '));
console.log('Revelações:', pf.revelacoes.map(r => r.caso + ': ' + r.armadilha.armadilha).join(' | '));
pf.feed.forEach(f => console.log('  feed:', f.texto));
const ro = h({ acao: 'prof_roteiro', codigo: 'S-2' });
ok(ro.partes.length === 4 && ro.cenario === 'vazamento' && ro.perguntas.length > 0, 'roteiro do pitch de grupo com vazamento');
ok(ro.perguntas[0].texto.indexOf('c11') >= 0 || /coluna/.test(ro.perguntas[0].texto), 'roteiro começa pela coluna de vazamento');
ok(/armadilha/.test(ro.central), 'roteiro aponta a armadilha');
const ra = h({ acao: 'prof_roteiro', codigo: 'A-1' });
ok(ra.cenario === 'drift' && ra.partes[2].pontos.some(p => p.rotulo === 'Agrupamento' && p.situacao === 'ok'), 'roteiro do agrupamento');
ok(s.handle({ acao: 'prof_roteiro', codigo: 'S-1' }).erro, 'roteiro exige senha');
if (process.argv[2] === '--roteiro') console.log(JSON.stringify(ro, null, 1));
const ex = h({ acao: 'prof_exportar' }); ok(ex.linhas.length === 5 && ex.linhas[0].length === ex.colunas.length, 'exportação');
const rv = h({ acao: 'estado', codigo: 'A-2' }).revelacao; ok(rv.fases[2].itens[2].correta.indexOf('4 grupos') === 0, 'revelação do agrupamento');
console.log(falhas ? falhas + ' FALHA(S)' : 'Tudo certo.');
process.exit(falhas ? 1 : 0);
